def explain(q, *texts):
    assert len(texts) == 4
    q['steps'] = [dict(title=t, text=s) for t, s in zip(TITLES, texts)]
    q['explanation'] = '\n\n'.join(f'{i+1}. {t}\n{s}' for i, (t,s) in enumerate(zip(TITLES,texts)))


def f(value):
    value=F(value)
    if value.denominator == 1:
        return str(value.numerator)
    d=value.denominator
    for prime in [2,5]:
        while d%prime==0:d//=prime
    if d==1:return f'{value}（{float(value):g}）'
    return str(value)


