def num(topic, prompt, value, unit, explanation, tip, level="基礎", table=None):
    f = Fraction(value)
    def fmt(v):
        v = Fraction(v)
        if v.denominator == 1:
            return str(v.numerator)
        if unit == "" or unit == "の確率":
            return f"{v.numerator}/{v.denominator}"
        return f"{v.numerator}/{v.denominator}"
    offsets = [1, 2, -1, 3, -2, 4, 5]
    step = 1 if abs(f) < 30 else (10 if abs(f) < 500 else 100)
    if f.denominator != 1:
        step = Fraction(1, f.denominator)
    wrong = []
    for offset in offsets:
        v = f + step * offset
        if v >= 0 and (unit != "の確率" or v <= 1):
            candidate = fmt(v) + ("" if unit == "の確率" else unit)
            if candidate not in wrong:
                wrong.append(candidate)
        if len(wrong) == 3:
            break
    if len(wrong) < 3:
        for v in [Fraction(0), Fraction(1, 4), Fraction(1, 2), Fraction(3, 4), Fraction(1)]:
            candidate = fmt(v) + ("" if unit == "の確率" else unit)
            if v != f and candidate not in wrong:
                wrong.append(candidate)
            if len(wrong) == 3:
                break
    ans = fmt(f) + ("" if unit == "の確率" else unit)
    add("非言語", topic, prompt, ans, wrong, explanation, tip, level, table,
        dict(expected=str(f), unit=unit))


