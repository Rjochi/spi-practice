def add(cat, topic, prompt, answer, wrong, explanation, tip, level="基礎", table=None, audit=None):
    choices = [str(answer)] + [str(x) for x in wrong]
    assert len(choices) == len(set(choices)), (topic, prompt, choices)
    idx = (len(QUESTIONS) * 7 + 3) % len(choices)
    choices.insert(idx, choices.pop(0))
    q = dict(id=f"q{len(QUESTIONS)+1:03}", category=cat, topic=topic, level=level,
             prompt=prompt, choices=choices, answer=idx, explanation=explanation, tip=tip)
    if table:
        q["table"] = table
    QUESTIONS.append(q)
    if audit:
        AUDIT.append(dict(id=q['id'], **audit))


def lang(topic, rows, tip):
    for i, row in enumerate(rows):
        prompt, answer, wrong, explanation = row
        add("言語", topic, prompt, answer, wrong, explanation, tip, "標準" if i >= 10 else "基礎")


